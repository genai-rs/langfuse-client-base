/// `uniqueItems`: no two items are equal.
fn check_unique_items<T: PartialEq>(items: &[T]) -> Result<(), ValidationError> {
    for (index, item) in items.iter().enumerate() {
        if let Some(first) = items[..index].iter().position(|earlier| earlier == item) {
            return Err(ValidationError::new(
                Rule::UniqueItems,
                format!("items {first} and {index} are equal"),
            ));
        }
    }
    Ok(())
}

