/// Sorts the errors a map's entries pushed from `start` on by their rendered (escaped) key, as a map iterates in no
/// fixed order.
#[doc(hidden)]
pub fn sort_by_key(errors: &mut [ValidationError], start: usize, path: &Path<'_>) {
    if errors.len() <= start + 1 {
        return;
    }
    let prefix = path.to_string().len();
    errors[start..].sort_by(|a, b| key_of(&a.path, prefix).cmp(key_of(&b.path, prefix)));
}

/// The `["key"]` segment that follows the map's own path.
fn key_of(path: &str, prefix: usize) -> &str {
    let rest = path.get(prefix..).unwrap_or("");
    let mut escaped = false;
    for (at, c) in rest.char_indices().skip(2) {
        match c {
            '\\' if !escaped => escaped = true,
            '"' if !escaped => return &rest[..at],
            _ => escaped = false,
        }
    }
    rest
}

