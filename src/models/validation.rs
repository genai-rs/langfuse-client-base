/// `minLength` and `maxLength`, in characters.
fn check_length(value: &str, min: Option<u64>, max: Option<u64>) -> Result<(), ValidationError> {
    let length = value.chars().count() as u64;
    if let Some(min) = min.filter(|min| length < *min) {
        return Err(ValidationError::new(
            Rule::MinLength(min),
            format!("length {length}"),
        ));
    }
    if let Some(max) = max.filter(|max| length > *max) {
        return Err(ValidationError::new(
            Rule::MaxLength(max),
            format!("length {length}"),
        ));
    }
    Ok(())
}

/// `minimum`
fn check_minimum<T: Number>(value: T, bound: T) -> Result<(), ValidationError> {
    if value < bound {
        return Err(ValidationError::new(
            Rule::Minimum(bound.as_f64()),
            value.to_string(),
        ));
    }
    Ok(())
}

