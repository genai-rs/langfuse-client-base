/// A number type a bound can apply to.
pub trait Number: Copy + PartialOrd + fmt::Display {
    /// The value as `f64`, to report a limit.
    fn as_f64(self) -> f64;
    /// Whether the value is a multiple of `factor`; for floating point numbers, within a relative tolerance.
    fn is_multiple(self, factor: Self) -> bool;
}

macro_rules! integer {
    ($($t:ty),*) => {$(
        impl Number for $t {
            fn as_f64(self) -> f64 {
                self as f64
            }
            fn is_multiple(self, factor: Self) -> bool {
                self.checked_rem(factor).is_none_or(|rest| rest == 0)
            }
        }
    )*};
}

integer!(i8, i16, i32, i64, u8, u16, u32, u64);

macro_rules! float {
    ($($t:ty => $tolerance:expr),*) => {$(
        impl Number for $t {
            fn as_f64(self) -> f64 {
                f64::from(self)
            }
            fn is_multiple(self, factor: Self) -> bool {
                let quotient = self / factor;
                (quotient - quotient.round()).abs() <= $tolerance * quotient.abs().max(1.0)
            }
        }
    )*};
}

